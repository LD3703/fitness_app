  const SeedHomeRoutine(
    this.slug,
    this.nameEn,
    this.nameCs,
    this.target,
    this.exerciseSlugs, {
    this.workSeconds = 45,
    this.restSeconds = 15,
  });

  final String slug;
  final String nameEn;
  final String nameCs;
  final MuscleGroup target;
  final List<String> exerciseSlugs;
  final int workSeconds;
  final int restSeconds;
}

